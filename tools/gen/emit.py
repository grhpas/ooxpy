"""Emitter: IR -> Python modules under ``src/oox``.

Output (all files carry a GENERATED header and are committed to the repo,
like odfpy's grammar.py, so users never need the SDK data):

``_generated/namespaces.py``  prefix/URI/version table
``_generated/index.py``       qname -> candidate keys
``_generated/enums.py``       enum facet values
``_generated/parts.py``       OPC part metadata (content/relationship types)
``_generated/p_<p>.py``       content-model trees (full validation), same grouping
``_generated/g_<p>.py``       grammar tables, one module per *type* prefix,
                              imported lazily by ``oox.grammar``
``ns/<p>.py``                 public factory functions, one module per
                              *element* prefix (``from oox.ns import w``)

Output is deterministic (sorted everywhere) so regeneration diffs are
reviewable and CI can assert "generated code is up to date".
"""

from __future__ import annotations

import keyword
import re
from collections import defaultdict
from pathlib import Path
from pprint import pformat

from .ir import Schema, TypeDef

FLAG_LEAF_TEXT, FLAG_ANY, FLAG_ORDERED, FLAG_ABSTRACT, FLAG_PART_ROOT = 1, 2, 4, 8, 16

_HEADER = '''\
# GENERATED by tools/gen from {source}.
# Do not edit by hand; run `python -m tools.gen --sdk-data <path>` instead.
'''


def modname(prefix: str) -> str:
    """Prefix -> safe module name (prefixes are identifiers, but be defensive)."""
    m = re.sub(r"\W", "_", prefix)
    return m + "_" if keyword.iskeyword(m) else m


def factory_name(local: str) -> str:
    ident = re.sub(r"\W", "_", local)
    ident = ident[:1].upper() + ident[1:]
    if not ident.isidentifier() or keyword.iskeyword(ident):
        ident = "E_" + ident
    return ident


def _flags(t: TypeDef) -> int:
    return (
        (FLAG_LEAF_TEXT if t.leaf_text else 0)
        | (FLAG_ANY if t.any_child else 0)
        | (FLAG_ORDERED if t.ordered else 0)
        | (FLAG_ABSTRACT if t.abstract else 0)
        | (FLAG_PART_ROOT if t.part_root else 0)
    )


_STUB_KINDS = {"bool": "bool | str", "tf": "bool | str", "int": "int | str",
               "float": "float | int | str", "datetime": "datetime | str", "list": "str",
               "hex": "str | bytes", "base64": "str | bytes"}


def _stub_type(attr, enums: dict) -> str:
    """Type hint for one attribute keyword in the ``.pyi`` stubs (permissive:
    the runtime converts and validates; the hint is for completion)."""
    if attr.kind == "enum" and attr.enum in enums and 0 < len(enums[attr.enum].values) <= 60:
        lits = ", ".join(repr(v) for v in enums[attr.enum].values)
        return f"Literal[{lits}] | str | None"
    return f"{_STUB_KINDS.get(attr.kind, 'str | int | float')} | None"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


RESERVED_KWARGS = frozenset({"text", "attributes", "qattributes", "parent", "check_grammar"})


def kwarg_names(qnames: list[str], element_prefix: str = "") -> dict[str, str]:
    """keyword -> attribute qname, by the same rule as ``oox.grammar._kwarg_map``
    (kept equal by tests/test_generator.py; the generator must not import oox,
    whose factory modules it is rewriting)."""
    import keyword

    locals_: dict[str, list[str]] = {}
    for q in qnames:
        locals_.setdefault(q.rpartition(":")[2], []).append(q)
    out: dict[str, str] = {}
    for local, qs in locals_.items():
        ident = local.replace("-", "_").replace(".", "_")
        for q in qs:
            prefix = q.rpartition(":")[0]
            if prefix:
                out[f"{prefix}_{ident}"] = q
        unqualified = [q for q in qs if ":" not in q]
        plain = qs[0] if len(qs) == 1 else (unqualified[0] if len(unqualified) == 1 else None)
        if plain is not None and ident in RESERVED_KWARGS and element_prefix and ":" not in plain:
            out.setdefault(f"{element_prefix}_{ident}", plain)
        if plain is None or not ident.isidentifier() or ident in RESERVED_KWARGS:
            continue
        out[ident + "_" if keyword.iskeyword(ident) else ident] = plain
    return out


def _stub_def(name: str, qname: str, keys, schema: Schema, prefix: str) -> str:
    """One stub signature: explicit keywords for the attributes (the union over
    the qname's content models), odfpy's keywords, and ``**attrs`` for the
    other spellings the runtime accepts."""
    by_qname: dict = {}
    for k in keys:
        for a in schema.types[k].attrs:
            by_qname.setdefault(a.qname, a)
    kw = kwarg_names(list(by_qname), qname.partition(":")[0])
    params = []
    for kwarg in sorted(kw):
        if kwarg in ("children", "attrs"):
            continue
        params.append(f"{kwarg}: {_stub_type(by_qname[kw[kwarg]], schema.enums)} = ...")
    params += ["attributes: dict[str, object] | None = ...",
               "qattributes: dict[tuple[str, str], object] | None = ...",
               "parent: OoxElement | None = ...", "check_grammar: bool = ...", "**attrs: object"]
    joined = ",\n    ".join(["*children: OoxElement | str", "text: str | None = ...", *params])
    return f"def {name}(\n    {joined},\n) -> OoxElement: ...\n"


def emit(schema: Schema, out_root: Path) -> dict[str, int]:
    hdr = _HEADER.format(source=schema.source)
    gen = out_root / "_generated"
    nsdir = out_root / "ns"
    for d in (gen, nsdir):  # clean slate so removed namespaces disappear
        if d.exists():
            for f in d.glob("*.py"):
                f.unlink()
    stats: dict[str, int] = {}

    known_prefixes = {n.prefix for n in schema.namespaces}

    # -- namespaces / enums / parts ------------------------------------------
    ns_rows = tuple(sorted((n.prefix, n.uri, n.version) for n in schema.namespaces))
    _write(gen / "namespaces.py", hdr + f"\nNAMESPACES = {pformat(ns_rows, width=100)}\n")
    enums = {k: e.values for k, e in sorted(schema.enums.items())}
    _write(gen / "enums.py", hdr + f"\nENUMS = {pformat(enums, width=100, compact=True)}\n")
    parts = {}
    multiple = {c["Name"] for p in schema.parts for c in p.get("Children", [])
                if c.get("MaxOccursGreatThanOne")}
    for p in schema.parts:
        parts[p["Name"]] = {
            "content_type": p.get("ContentType"),
            "relationship_type": p.get("RelationshipType"),
            "target": p.get("Target"),
            "extension": p.get("Extension"),
            "path": (p.get("Paths") or {}).get("General"),
            "root": p.get("Root"),
            "children": tuple(sorted(c["Name"] for c in p.get("Children", []))),
            "multiple": p["Name"] in multiple,  # may occur more than once per parent
        }
    _write(gen / "parts.py", hdr + f"\nPARTS = {pformat(dict(sorted(parts.items())), width=100)}\n")
    _write(gen / "__init__.py", hdr + f'\nSOURCE = {schema.source!r}\n')

    # -- grammar tables, grouped by type prefix -------------------------------
    by_module: dict[str, dict[str, tuple]] = defaultdict(dict)
    candidates: dict[str, list[str]] = defaultdict(list)
    for key in sorted(schema.types):
        t = schema.types[key]
        tprefix = key.partition("/")[0].partition(":")[0]
        attrs = tuple((a.qname, a.kind, a.required, a.enum, a.version, a.lexical)
                      for a in t.attrs)
        kids = tuple(
            (c.key, c.rank, c.max_one, c.required, c.version)
            for c in sorted(t.children, key=lambda c: (c.rank, c.key))
        )
        by_module[modname(tprefix)][key] = (t.qname, _flags(t), attrs, kids, t.version)
        if t.qname and not t.abstract:
            candidates[t.qname].append(key)
    for mod, table in sorted(by_module.items()):
        _write(gen / f"g_{mod}.py", hdr + f"\nTYPES = {pformat(table, width=110, compact=True)}\n")
    # content-model trees for full validation, in their own modules: loaded
    # only by validate(level="full")
    particles: dict[str, dict[str, tuple]] = defaultdict(dict)
    for key in sorted(schema.types):
        t = schema.types[key]
        if t.particle is not None and t.qname and not t.abstract:
            particles[modname(key.partition("/")[0].partition(":")[0])][key] = t.particle
    for mod, table in sorted(particles.items()):
        _write(gen / f"p_{mod}.py",
               hdr + f"\nPARTICLES = {pformat(table, width=110, compact=True)}\n")
    stats["particles"] = sum(len(t) for t in particles.values())
    index = {q: tuple(sorted(ks)) for q, ks in sorted(candidates.items())}
    _write(gen / "index.py", hdr + f"\nCANDIDATES = {pformat(index, width=110, compact=True)}\n")
    stats["types"] = len(schema.types)
    stats["qnames"] = len(index)
    stats["ambiguous_qnames"] = sum(len(v) > 1 for v in index.values())

    # -- public factory modules, grouped by element prefix --------------------
    by_elprefix: dict[str, list[str]] = defaultdict(list)
    for q in index:
        p = q.partition(":")[0] if ":" in q else ""
        if p not in known_prefixes:
            schema.warnings.append(f"element without known prefix skipped: {q}")
            continue
        by_elprefix[p].append(q)

    uri_of = {n.prefix: n.uri for n in schema.namespaces}
    n_factories = n_aliases = 0
    for prefix, qnames in sorted(by_elprefix.items()):
        used: set[str] = set()
        lines = [
            hdr,
            f'"""Factories for namespace ``{prefix}`` ({uri_of[prefix]}).',
            "",
            "Each function creates one element; children may be passed positionally",
            "and are inserted in schema order.  Attributes are keyword arguments named",
            "after the attribute's local name (``val=``), or ``prefix_local`` when",
            "ambiguous (``r_id=``).  SDK class-name aliases (e.g. ``Paragraph``) bind a",
            "specific content model where a qname has several.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "from oox.element import OoxElement, make as _make",
            "",
        ]
        alias_lines: list[str] = []
        stub = [hdr, f'"""Type stubs for ``oox.ns.{modname(prefix)}`` (keyword completion)."""', "",
                "from __future__ import annotations", "", "from datetime import datetime",
                "from typing import Literal", "", "from oox.element import OoxElement", ""]
        stub_names: dict[str, str] = {}
        for q in sorted(qnames):
            keys = index[q]
            local = q.partition(":")[2]
            name = factory_name(local)
            while name in used:
                schema.warnings.append(f"factory name collision in {prefix}: {q} -> {name}_")
                name += "_"
            used.add(name)
            summaries = sorted({schema.types[k].summary for k in keys} - {""})
            if len(summaries) == 1:
                doc_summary = summaries[0]
            else:  # don't pick an arbitrary content model's summary
                doc_summary = f"``{local}`` element ({len(keys)} content models)."
            doc_summary = doc_summary.replace('"""', "'''").replace("\\", "\\\\")
            types_doc = ", ".join(k.partition("/")[0] for k in keys)
            attr_names = sorted({a.qname for k in keys for a in schema.types[k].attrs})
            lines += [
                "",
                f"def {name}(*children, text: str | None = None, **attrs) -> OoxElement:",
                f'    """{doc_summary}',
                "",
                f"    ``<{q}>`` -- content model: {types_doc}"
                + ("  (resolved from parent)" if len(keys) > 1 else ""),
            ]
            if attr_names:
                lines.append(f"    Attributes: {', '.join(attr_names)}")
            lines += ['    """', f"    return _make({q!r}, None, children, text, attrs)", ""]
            stub_names[name] = _stub_def(name, q, keys, schema, prefix)
            n_factories += 1
            for k in keys:
                alias = schema.types[k].class_name
                if not alias.isidentifier() or alias == name:
                    continue
                if len(keys) == 1:
                    alias_lines.append((alias, f"{alias} = {name}"))
                else:
                    alias_lines.append((alias, (
                        f"def {alias}(*children, text: str | None = None, **attrs) -> OoxElement:\n"
                        f'    """``<{q}>`` bound to content model ``{k.partition("/")[0]}``."""\n'
                        f"    return _make({q!r}, {k!r}, children, text, attrs)\n")))
        lines += ["", "# --- SDK class-name aliases ---", ""]
        alias_stubs: list[str] = []
        for alias, code in sorted(alias_lines):
            if alias in used:
                continue  # never shadow a qname factory
            used.add(alias)
            lines.append(code)
            if code.startswith(f"{alias} = "):
                alias_stubs.append(code)
            else:
                qn = code.split("_make(", 1)[1].split(",", 1)[0].strip("'")
                ky = code.split("_make(", 1)[1].split(",", 2)[1].strip().strip("'")
                alias_stubs.append(_stub_def(alias, qn, (ky,), schema, prefix))
            n_aliases += 1
        _write(nsdir / f"{modname(prefix)}.py", "\n".join(lines) + "\n")
        stub += [stub_names[n] for n in sorted(stub_names)] + ["", "# SDK class-name aliases", ""]
        stub += alias_stubs
        _write(nsdir / f"{modname(prefix)}.pyi", "\n".join(stub) + "\n")
    mods = sorted(modname(p) for p in by_elprefix)
    consts = {p.upper(): u for p, u, _ in ns_rows}
    if len(consts) != len(ns_rows):
        raise ValueError("two namespace prefixes differ only in case")
    init = [hdr, '"""Namespaces: a constant per prefix holding its URI (``W``, ``A``, ``R``,',
            '``MC`` ...), ``qn("w:p")`` for the ``{uri}local`` name lxml uses, and the',
            "element factory modules, one per prefix (``w``, ``a`` ...).",
            "",
            "    from oox.ns import W, qn, w",
            '    paragraphs = body.iter(f"{{{W}}}p")      # same as body.iter(qn("w:p"))',
            '    p = w.P(w.R(w.T("text")))',
            '"""',
            "",
            "from __future__ import annotations",
            ""]
    init += [f"{name} = {uri!r}" for name, uri in sorted(consts.items())]
    init += ["",
             "_URI = {" + ", ".join(f"{p!r}: {p.upper()}" for p, _, _ in ns_rows) + "}",
             "",
             "",
             "def qn(name: str) -> str:",
             '    """``"w:p"`` -> ``"{http://...wordprocessingml/2006/main}p"``; a name',
             '    without a prefix is returned as it is."""',
             '    prefix, _, local = name.rpartition(":")',
             '    return f"{{{_URI[prefix]}}}{local}" if prefix else local',
             "",
             "",
             f"__all__ = {pformat([*sorted(consts), 'qn', *mods], width=100, compact=True)}"]
    _write(nsdir / "__init__.py", "\n".join(init) + "\n")
    stats["factories"] = n_factories
    stats["aliases"] = n_aliases
    stats["ns_modules"] = len(mods)
    return stats
