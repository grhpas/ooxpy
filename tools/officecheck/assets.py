_BLUE, _WHITE, _RED = 0x00965430, 0x00FFFFFF, 0x000000C0  # COLORREF: 0x00BBGGRR


def _emf() -> bytes:
    """A 160x80 px EMF (blue rectangle, white ellipse), written record by record."""
    import struct

    def rec(kind: int, payload: bytes) -> bytes:
        return struct.pack("<II", kind, 8 + len(payload)) + payload

    body = b"".join([
        rec(39, struct.pack("<IIII", 1, 0, _BLUE, 0)),      # EMR_CREATEBRUSHINDIRECT
        rec(37, struct.pack("<I", 1)),                      # EMR_SELECTOBJECT
        rec(43, struct.pack("<iiii", 0, 0, 160, 80)),       # EMR_RECTANGLE
        rec(39, struct.pack("<IIII", 2, 0, _WHITE, 0)),
        rec(37, struct.pack("<I", 2)),
        rec(42, struct.pack("<iiii", 30, 15, 130, 65)),     # EMR_ELLIPSE
        rec(14, struct.pack("<III", 0, 16, 20)),            # EMR_EOF
    ])
    n_records = 7 + 1
    total = 108 + len(body)
    header = struct.pack(
        "<II4i4iIIIIHHIII2i2iIII2i",
        1, 108,                       # EMR_HEADER, size
        0, 0, 159, 79,                # rclBounds (device pixels, inclusive)
        0, 0, 4233, 2116,             # rclFrame (0.01 mm): 160x80 px at 96 dpi
        0x464D4520, 0x10000, total, n_records, 3, 0,  # " EMF", version, bytes, records, handles
        0, 0, 0,                      # description, palette
        1024, 768, 271, 203,          # reference device: pixels, millimetres (96 dpi)
        0, 0, 0,                      # pixel format, OpenGL
        270933, 203200,               # reference device in micrometres
    )
    return header + body


def _wmf() -> bytes:
    """A placeable WMF, 160x80 units at 96 per inch, same picture as the EMF."""
    import struct

    def rec(func: int, *params: int) -> bytes:
        return struct.pack("<IH", 3 + len(params), func) + struct.pack("<%dh" % len(params), *params)

    def brush(color: int) -> bytes:  # META_CREATEBRUSHINDIRECT: style, colorref, hatch
        return struct.pack("<IHHIH", 7, 0x02FC, 0, color, 0)

    records = [
        rec(0x020B, 0, 0),                 # META_SETWINDOWORG (y, x)
        rec(0x020C, 80, 160),              # META_SETWINDOWEXT (height, width)
        brush(_BLUE), rec(0x012D, 0),      # brush 0, META_SELECTOBJECT
        rec(0x041B, 80, 160, 0, 0),        # META_RECTANGLE (bottom, right, top, left)
        brush(_WHITE), rec(0x012D, 1),
        rec(0x0418, 65, 130, 15, 30),      # META_ELLIPSE
        rec(0x0000),                       # META_EOF
    ]
    body = b"".join(records)
    words = 9 + len(body) // 2
    largest = max(len(r) // 2 for r in records)
    meta = struct.pack("<HHHIHIH", 1, 9, 0x0300, words, 2, largest, 0)
    head = struct.pack("<IhhhhhHI", 0x9AC6CDD7, 0, 0, 0, 160, 80, 96, 0)
    checksum = 0
    for (w,) in struct.iter_unpack("<H", head):
        checksum ^= w
    return head + struct.pack("<H", checksum) + meta + body


_SVG = (b'<svg xmlns="http://www.w3.org/2000/svg" width="160" height="80" viewBox="0 0 160 80">'
        b'<rect width="160" height="80" fill="#2F5496"/>'
        b'<ellipse cx="80" cy="40" rx="50" ry="25" fill="#FFFFFF"/>'
        b'<polygon points="80,22 98,52 62,52" fill="#C00000"/></svg>')


def image(fmt: str) -> bytes:
    """fmt: PNG, JPEG, GIF, BMP, TIFF, EMF, WMF or SVG."""
    if fmt == "EMF":
        return _emf()
    if fmt == "WMF":
        return _wmf()
    if fmt == "SVG":
        return _SVG
    return base64.b64decode(_DATA[fmt])
